// YGO Sandbox for Windows: the same screens and logic as the phone app (../shared), in a desktop
// window. The GitHub build puts the engine's ygoe_jni.dll in resources/windows/ and its card pack
// in resources/common/ygoe/ (see .github/workflows/build.yml), then packages an MSI installer.
import org.jetbrains.compose.desktop.application.dsl.TargetFormat

plugins {
    id("org.jetbrains.kotlin.jvm")
    id("org.jetbrains.compose")
    id("org.jetbrains.kotlin.plugin.compose")
}

// Same numbering as the APK: every GitHub build is 0.0.<run number>.
val buildNumber = System.getenv("GITHUB_RUN_NUMBER")?.toIntOrNull() ?: 0
val appVersion = "0.0.$buildNumber"

kotlin {
    jvmToolchain(17)
}

// The app's version as a constant (the desktop has no BuildConfig).
val versionDir = layout.buildDirectory.dir("generated/version")
val generateVersion = tasks.register("generateVersion") {
    val out = versionDir.get().file("com/ygosandbox/desktop/DesktopVersion.kt").asFile
    inputs.property("version", appVersion)
    outputs.file(out)
    doLast {
        out.parentFile.mkdirs()
        out.writeText(
            "package com.ygosandbox.desktop\n\n/** Generated by desktop/build.gradle.kts. */\n" +
                "object DesktopVersion {\n    const val NAME = \"$appVersion\"\n}\n",
        )
    }
}

sourceSets {
    main {
        kotlin.srcDirs("src/main/kotlin", "../shared/src/main/kotlin", versionDir)
    }
}

tasks.named("compileKotlin") { dependsOn(generateVersion) }

dependencies {
    implementation(compose.desktop.currentOs)
    implementation(compose.material3)
    implementation(compose.materialIconsExtended)
    implementation("org.jetbrains.androidx.lifecycle:lifecycle-viewmodel-compose:2.8.4")
    implementation("org.jetbrains.androidx.lifecycle:lifecycle-runtime-compose:2.8.4")
    implementation("org.jetbrains.kotlinx:kotlinx-coroutines-swing:1.9.0")

    implementation(project(":ygoe-jvm"))

    implementation("io.coil-kt.coil3:coil-compose:3.0.4")
    implementation("io.coil-kt.coil3:coil-network-okhttp:3.0.4")
    implementation("com.google.code.gson:gson:2.11.0")
    implementation("org.json:json:20240303")
    // Combos/Replays: YouTube search (reading the videos themselves is phone-only for now).
    implementation("com.github.teamnewpipe:NewPipeExtractor:v0.26.5")
}

compose.desktop {
    application {
        mainClass = "com.ygosandbox.desktop.MainKt"
        // A crash of the JVM itself (native code) leaves its report next to the app instead of
        // wherever the app was started from.
        jvmArgs += listOf("-Xmx3g", "-XX:ErrorFile=\$APPDIR/../hs_err_pid%p.log")

        nativeDistributions {
            targetFormats(TargetFormat.Msi)
            packageName = "YGO Sandbox"
            // MSI versions must start above 0, so the installer counts 1.0.<run>; the app shows 0.0.<run>.
            packageVersion = "1.0.$buildNumber"
            description = "Yu-Gi-Oh! deck testing and learning"
            vendor = "0megaXP"
            appResourcesRootDir.set(layout.projectDirectory.dir("resources"))
            // The whole Java runtime: HTTPS, logging and the libraries' optional parts all work.
            includeAllModules = true

            windows {
                // Installs for the current user (no administrator prompt), so updates can run silently.
                perUserInstall = true
                menu = true
                menuGroup = "YGO Sandbox"
                shortcut = true
                // Fixed, so each new MSI upgrades the installed app instead of installing a second copy.
                upgradeUuid = "6f1c2c9e-8d5a-4b3e-9c41-3b7e1a2d5f60"
            }
        }
    }
}
